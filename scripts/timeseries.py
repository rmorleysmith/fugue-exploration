"""The dynamical view: a driven particle in one well of |F|², and the spectrum of its motion.

WHAT IT COMPUTES — F(q) = q − q₀ with a single zero at τ₀ = 0.5 + 0.45i (coefficient vector
    normalised to max modulus 1), so |F|² is one anharmonic well in the τ-strip. The state is
    driven by a single tone u(t) = sin(2π·0.22·t):
        τ̇ = −α clip(∇|F|²) + B u(t),   α = 0.8,  B = (0.22, 0.07),  dt = 0.02,  3000 steps.
    The time series Re τ(t) is Fourier-analysed after a 400-step transient; its power
    spectrum is compared with the drive's.
WHAT THE FIGURE SHOWS — Left: the input tone and the normalised motion Re τ(t). Middle: the
    path in the τ-plane around the zero. Right: the Hann-windowed amplitude spectrum of the
    motion against that of the input on a log scale, with the drive tone and its harmonics
    2f₀, 3f₀ marked; the harmonics are about 1% and 0.1% of the fundamental.
WHAT IS PROVED / KNOWN — A periodically driven nonlinear first-order system responds at the
    drive frequency and its harmonics (standard harmonic balance; Strogatz, "Nonlinear
    Dynamics and Chaos", ch. 7–8 for the driven overdamped case). The restoring force here is
    anharmonic because q = e^{2πiτ} is periodic in Re τ. The particular harmonic content is a
    measurement of this well, this drive and this amplitude.
WHAT IS NOT CLAIMED — The June title said the particle moves "in the E8 modular form". It
    does not: the landscape is a one-zero polynomial in q, not E₄ (THE-STORY §3). The
    June panel used a rectangular window on a linear axis, where the spectral leakage of the
    drive itself (5% at 2f₀) exceeded the harmonic it pointed at; with a Hann window the
    harmonics are real but weak (about 1%). The response is mildly nonlinear, as any
    anharmonic well's is at small amplitude; nothing
    arithmetic is read from it, and "Fourier analysis of the movement" is a description of
    the plot, not a theorem about modular forms. Fourier and spectral analysis of the
    physical side is the right next question, and this script
    is only its first picture.
HOW THIS WAS FOUND — We had been treating the flow as a routing device and wanted to see it
    as physics: a particle driven through a potential and the spectrum of its motion. The
    picture was a bead on a corrugated wire shaken at one frequency, which rattles at the
    overtones. The precise statement is the nonlinear-response one above.
"""
from __future__ import annotations

from pathlib import Path

import numpy as np
import jax
import jax.numpy as jnp
from jax import grad, lax

jax.config.update("jax_enable_x64", True)


def energy(coeffs, xy):
    q = jnp.exp(2j * jnp.pi * (xy[0] + 1j * xy[1]))
    f = jnp.sum(coeffs * q ** jnp.arange(coeffs.shape[0]))
    return jnp.real(f * jnp.conj(f))


_genergy = grad(energy, argnums=1)

# a single anharmonic well (one zero): a moderate drive keeps the particle inside the well
_zeros = np.array([0.50 + 0.45j])
_c = np.poly(np.exp(2j * np.pi * _zeros))[::-1]
_c = _c / np.max(np.abs(_c))
COEFFS = jnp.asarray(_c.astype(complex))


def driven(coeffs, u, x0, dt=0.02, alpha=0.8, B=(0.22, 0.07)):
    B = jnp.asarray(B)
    gmax = 4.0

    def step(xy, ut):
        g = _genergy(coeffs, xy)
        g = jnp.clip(g, -gmax, gmax)
        v = -alpha * g + B * ut
        nx = jnp.clip(xy[0] + dt * v[0], 0.08, 0.92)
        ny = jnp.clip(xy[1] + dt * v[1], 0.28, 0.64)
        n = jnp.array([nx, ny])
        return n, n
    _, tr = lax.scan(step, jnp.asarray(x0), u)
    return tr


def run(make_fig=True):
    T, dt = 3000, 0.02
    t = np.arange(T) * dt
    f0 = 0.22                                   # single drive tone
    u = 1.0 * np.sin(2 * np.pi * f0 * t)

    tr = np.array(driven(COEFFS, jnp.asarray(u), [0.5, 0.46]))
    x, y = tr[:, 0], tr[:, 1]

    s = 400                                     # drop the transient
    win = np.hanning(T - s)                     # Hann window: keeps spectral leakage below 1e-3
    freqs = np.fft.rfftfreq(T - s, dt)
    Uf = np.abs(np.fft.rfft((u[s:] - u[s:].mean()) * win))
    Xf = np.abs(np.fft.rfft((x[s:] - x[s:].mean()) * win))
    Xf /= Xf.max() + 1e-12
    Uf /= Uf.max() + 1e-12

    def amp_at(spec, f):
        return float(spec[np.argmin(np.abs(freqs - f))])

    print(f"trajectory: Re tau in [{x.min():.3f},{x.max():.3f}], Im tau in [{y.min():.3f},{y.max():.3f}]")
    a1, a2, a3 = amp_at(Xf, f0), amp_at(Xf, 2 * f0), amp_at(Xf, 3 * f0)
    u2, u3 = amp_at(Uf, 2 * f0), amp_at(Uf, 3 * f0)
    print(f"drive tone {f0}: motion spectrum at f0, 2f0, 3f0 = {a1:.3f}, {a2:.3f}, {a3:.3f}; "
          f"input at 2f0, 3f0 = {u2:.3f}, {u3:.3f}")
    assert np.argmax(Xf) == np.argmin(np.abs(freqs - f0)), "the motion's main peak is not the drive tone"
    assert a2 > 10 * u2 and a3 > 10 * u3, "no harmonics generated by the well"
    assert a2 < 0.1, "unexpectedly strong harmonics; the 'weak' wording below would be wrong"
    print(f"weak harmonics at 2f0 and 3f0 ({a2*100:.1f}% and {a3*100:.2f}% of the fundamental) are present in "
          "the motion and absent from the drive: a mildly nonlinear response at this amplitude, measured")

    if make_fig:
        _figure(t, u, x, y, tr, freqs, Uf, Xf, f0)
    return tr


def _figure(t, u, x, y, tr, freqs, Uf, Xf, f0):
    import matplotlib.pyplot as plt
    import style  # noqa: F401

    TEAL, GOLD, NEURON = "#46f0d0", "#ffd166", "#ff3b6b"

    fig = plt.figure(figsize=(15.5, 5.2))
    gs = fig.add_gridspec(1, 3, width_ratios=[1.25, 0.85, 1.1])
    a, b, c = (fig.add_subplot(gs[0]), fig.add_subplot(gs[1]), fig.add_subplot(gs[2]))

    w = slice(400, 1200)
    a.plot(t[w], u[w], color="#888", lw=1.4, label="input  $u(t)$")
    a.plot(t[w], (x[w] - x[w].mean()) / (x[w].std() + 1e-9), color=TEAL, lw=1.8,
           label=r"motion  $\mathrm{Re}\,\tau(t)$ (norm.)")
    a.set_xlabel("time"); a.set_ylabel("signal")
    a.set_title("a particle driven in one well of $|F|^2$\n(the state as a time series)", fontsize=12)
    a.legend(loc="upper right", fontsize=9, framealpha=0.3)

    b.set_facecolor("#0b0b14")
    b.plot(tr[400:, 0], tr[400:, 1], color=GOLD, lw=0.7, alpha=0.8)
    b.plot(_zeros.real, _zeros.imag, "o", color=NEURON, ms=10, mec="white", mew=0.6,
           label="the zero of $F$")
    b.set_xlabel(r"$\mathrm{Re}\,\tau$"); b.set_ylabel(r"$\mathrm{Im}\,\tau$")
    b.set_title("its path in $\\mathbb{H}$", fontsize=12)
    b.legend(loc="upper right", fontsize=8, framealpha=0.3)

    c.semilogy(freqs, Uf + 1e-7, color="#888", lw=1.4, label="input (one tone)")
    c.semilogy(freqs, Xf + 1e-7, color=TEAL, lw=1.6, label="motion")
    c.set_ylim(1e-5, 2)
    c.axvline(f0, color=NEURON, ls=":", lw=1, alpha=0.7)
    for h in (2, 3):
        c.axvline(h * f0, color=GOLD, ls=":", lw=1, alpha=0.5)
    c.annotate("drive\ntone", (f0 + 0.015, 0.5), color=NEURON, fontsize=8)
    c.annotate("weak harmonics (~1%)\nfrom the anharmonic well", (2 * f0 + 0.015, 0.02), color=GOLD, fontsize=8)
    c.set_xlim(0, 0.9); c.set_xlabel("frequency"); c.set_ylabel("amplitude (norm., log, Hann window)")
    c.set_title("spectrum of the motion", fontsize=12)
    c.legend(loc="upper right", fontsize=8.5, framealpha=0.3)

    fig.suptitle("The dynamical view: a driven first-order flow on a one-zero landscape $|q-q_0|^2$ responds at "
                 "the drive tone with weak harmonics\n(a mildly nonlinear response at this amplitude, not a modular property)",
                 fontsize=12.5, y=1.04)
    out = Path(__file__).parent.parent / "figures" / "27_timeseries.png"
    fig.savefig(out, dpi=170, bbox_inches="tight")
    plt.close(fig)
    print(f"wrote {out}")


if __name__ == "__main__":
    run()
